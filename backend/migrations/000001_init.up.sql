CREATE TABLE roles (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) UNIQUE NOT NULL CHECK (name IN ('admin', 'teacher', 'student', 'dean')),
    description TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE resources (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) UNIQUE NOT NULL,
    description TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE users (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      CITEXT UNIQUE NOT NULL,
    email         CITEXT UNIQUE NOT NULL,
    password_hash TEXT   NOT NULL CHECK (length(password_hash) >= 20),
    status        VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'blocked', 'pending')),
    is_active     BOOLEAN     NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (position('@' IN email::TEXT) > 1)
);

CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- One user has one active system role. Composite PK is kept for backend
-- compatibility, UNIQUE(user_id) enforces the "one user - one role" rule.
CREATE TABLE user_roles (
    user_id     INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id     INT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, role_id),
    UNIQUE (user_id)
);

-- Kept as acl_entries because the current Go repository queries it directly.
CREATE TABLE acl_entries (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id     INT NOT NULL REFERENCES roles(id)     ON DELETE CASCADE,
    resource_id INT NOT NULL REFERENCES resources(id) ON DELETE CASCADE,
    can_read    BOOLEAN NOT NULL DEFAULT FALSE,
    can_write   BOOLEAN NOT NULL DEFAULT FALSE,
    can_delete  BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (role_id, resource_id)
);

CREATE TRIGGER trg_acl_entries_updated_at
BEFORE UPDATE ON acl_entries
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE VIEW acl AS
SELECT
    a.id,
    a.role_id,
    r.name AS role_name,
    a.resource_id,
    res.name AS resource_name,
    a.can_read,
    a.can_write,
    a.can_delete,
    a.created_at,
    a.updated_at
FROM acl_entries a
JOIN roles r ON r.id = a.role_id
JOIN resources res ON res.id = a.resource_id;

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INT REFERENCES users(id) ON DELETE SET NULL,
    action      VARCHAR(255) NOT NULL,
    resource    VARCHAR(100),
    resource_id TEXT,
    ip_address  INET,
    user_agent  TEXT,
    metadata    JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

