CREATE POLICY vedomost_admin_all ON vedomost
    FOR ALL
    USING (app_current_role() = 'admin')
    WITH CHECK (app_current_role() = 'admin');

CREATE POLICY discipliny_admin_all ON discipliny
    FOR ALL
    USING (app_current_role() = 'admin')
    WITH CHECK (app_current_role() = 'admin');

CREATE POLICY dean_vedomost ON vedomost
    FOR ALL
    USING (
        app_current_role() = 'dean'
        AND id_predmeta IN (
            SELECT d.id FROM discipliny d
            WHERE d.id_kafedry = app_current_kafedra_id()
        )
    )
    WITH CHECK (
        app_current_role() = 'dean'
        AND id_predmeta IN (
            SELECT d.id FROM discipliny d
            WHERE d.id_kafedry = app_current_kafedra_id()
        )
    );

CREATE POLICY dean_discipliny ON discipliny
    FOR ALL
    USING (app_current_role() = 'dean' AND id_kafedry = app_current_kafedra_id())
    WITH CHECK (app_current_role() = 'dean' AND id_kafedry = app_current_kafedra_id());

